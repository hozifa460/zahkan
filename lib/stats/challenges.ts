/** تحدي بمعرّفه */
export function getChallengeById(id: string): Challenge30Day | undefined {
  return CHALLENGES_30.find((c) => c.id === id);
}

/** جلب مهمة اليوم من تحدي */
export function getChallengeDayTask(challengeId: string, day: number): ChallengeDay | undefined {
  const challenge = getChallengeById(challengeId);
  return challenge?.days.find((d) => d.day === day);
}

/** قائمة التحديات */
export function getAllChallenges(): Challenge30Day[] {
  return CHALLENGES_30;
}
